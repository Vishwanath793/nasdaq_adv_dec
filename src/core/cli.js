/**
 * Command line:
 *   npm run demo -- [--date 2026-10-19] [--seed 20261019]   deterministic DEMO session → .data/sessions/
 *   npm run replay -- <sessionId> [--preset equalGroups]      replay a stored session (research copy)
 *   npm run validate -- [--days 12]                            multi-day DEMO validation + ablation → docs/VALIDATION_RESULTS.md
 *   npm run registry                                           write docs/CAPABILITY_MATRIX.md from the registry
 */

import fs from 'node:fs';
import { loadEnv } from './env.js';
import { runDemo, replay, loadSession, rescore } from './sessions.js';
import { loadSettings } from './settings.js';
import { reportCard, ablation } from '../utils/reportCard.js';
import { SOURCES, PROFILE_FEATURES, MODES } from './registry.js';
import { readJson } from './store.js';
import { previousTradingDays } from '../utils/clock.js';

loadEnv();
const [cmd, ...rest] = process.argv.slice(2);
const opt = (name, d = null) => { const i = rest.indexOf(`--${name}`); return i >= 0 ? rest[i + 1] : d; };
const pct = (x, d = 2) => (x == null ? 'n/a' : `${x.toFixed(d)}%`);
const f2 = (x) => (x == null ? 'n/a' : x.toFixed(2));

function demo() {
  const date = opt('date', '2026-10-19');
  const seed = Number(opt('seed', 20261019));
  const t = Date.now();
  const r = runDemo({ date, seed, config: loadSettings() });
  console.log(`DEMO session ${r.id} (${Date.now() - t} ms)`);
  console.log(JSON.stringify(r, null, 2));
}

function doReplay() {
  const id = rest.find((x) => !x.startsWith('--'));
  if (!id) { console.error('usage: npm run replay -- <sessionId> [--preset name]'); process.exit(1); }
  const preset = opt('preset');
  const r = replay(id, { config: { ...loadSettings(), ...(preset ? { preset } : {}) }, label: preset ? `preset ${preset}` : 'cli replay' });
  console.log(JSON.stringify(r, null, 2));
}

function validate() {
  const n = Number(opt('days', 12));
  const dates = previousTradingDays('2026-10-20', n).reverse();
  const ids = [];
  for (const [i, date] of dates.entries()) { const r = runDemo({ date, seed: 1000 + i, config: loadSettings() }); ids.push(r.id); process.stdout.write('.'); }
  console.log();
  const sessions = ids.map((id) => loadSession(id));
  const rc = reportCard(sessions, { horizon: 'm30' });
  const presets = ['gapOnly', 'gapRvol', 'priceVolumeNoNews', 'equalGroups', 'volumeFirst', 'fullFree'];
  const ab = ablation(rescore(ids, presets, loadSettings()), { horizon: 'm30' });
  // Determinism: replay the first session under the same settings and compare.
  const rep = replay(ids[0], { config: loadSettings(), label: 'determinism check' });
  const lines = [
    '# Validation results (DEMO, generated)', '',
    `Generated by \`npm run validate\` on ${new Date().toISOString()} over ${ids.length} simulated sessions (${dates[0]} … ${dates.at(-1)}).`, '',
    '> **These sessions are simulated.** They validate the mechanics (no look-ahead, determinism, coverage handling, labels, paper fills) — they say nothing about real-market edge. Real validation needs recorded LIVE or DELAYED sessions.', '',
    `Determinism: replay of ${ids[0]} under the same settings produced ${rep.identicalToOriginal ? 'IDENTICAL' : 'DIFFERENT'} pre-open decisions.`, '',
    `Observations: ${rc.observations}; rank correlation (score vs 30-min return in the scored direction): ${f2(rc.rankCorrelation)}; continuation rate (60 min): ${pct((rc.continuationRate ?? 0) * 100, 0)}.`, '',
    '## Score bands (09:28 snapshot, 30-minute return in the scored direction, before costs)', '',
    '| Band | n | Mean | Median | 90% CI (bootstrap) | Hit rate | Mean MFE (60m) | Mean MAE (60m) | Note |', '|---|---|---|---|---|---|---|---|---|',
    ...rc.bands.map((b) => `| ${b.band} | ${b.n} | ${pct(b.meanRet)} | ${pct(b.medianRet)} | ${b.ci90 ? `${pct(b.ci90[0])} … ${pct(b.ci90[1])}` : 'n/a'} | ${b.hitRate == null ? 'n/a' : pct(b.hitRate * 100, 0)} | ${pct(b.meanMfe)} | ${pct(b.meanMae)} | ${b.note} |`), '',
    '## Ablation (chronological split: first 60% of dates = development, rest = held out)', '',
    '| Preset | n | dev n | test n | dev rank corr | test rank corr | test top-quintile mean | Note |', '|---|---|---|---|---|---|---|---|',
    ...ab.map((a) => `| ${a.preset} | ${a.n} | ${a.devN} | ${a.testN} | ${f2(a.devRankCorr)} | ${f2(a.testRankCorr)} | ${pct(a.testTopQuintileRet)} | ${a.note} |`), '',
    '## Opening confirmation verdicts (30-minute return after the seal)', '',
    '| Verdict | n | Mean | Hit rate |', '|---|---|---|---|', ...rc.confirmation.map((c) => `| ${c.verdict} | ${c.n} | ${pct(c.meanRet)} | ${pct(c.hitRate * 100, 0)} |`), '',
    '## Decisions and coverage', '',
    `No-trade rate ${pct((rc.decisions.noTradeRate ?? 0) * 100, 0)}, insufficient-evidence rate ${pct((rc.decisions.insufficientRate ?? 0) * 100, 0)}, blocked rate ${pct((rc.decisions.blockedRate ?? 0) * 100, 0)}, paper entries ${rc.decisions.paperEntries}.`, '',
    'Top primary reasons: ' + rc.decisions.topReasons.map(([k, v]) => `${k} (${v})`).join('; '), '',
    '## Paper simulation (after modelled costs)', '',
    `Trades ${rc.paper.trades}, net $${f2(rc.paper.netTotal)}, expectancy $${f2(rc.paper.expectancy)}/trade, win rate ${rc.paper.winRate == null ? 'n/a' : pct(rc.paper.winRate * 100, 0)}, max drawdown $${f2(rc.paper.maxDrawdown)}, costs $${f2(rc.paper.costs)}. ${rc.paper.note}.`, '',
    `Hypothetical shorts (borrow not verified, not executable): n=${rc.paper.hypotheticalShorts.n}, net $${f2(rc.paper.hypotheticalShorts.net)}.`, '',
  ];
  fs.mkdirSync('docs', { recursive: true });
  fs.writeFileSync('docs/VALIDATION_RESULTS.md', lines.join('\n'));
  console.log(lines.slice(0, 14).join('\n'));
  console.log('… written to docs/VALIDATION_RESULTS.md');
}

function registry() {
  const probe = readJson('probe-results.json');
  const verified = new Map((probe?.results ?? []).map((r) => [r.id, r]));
  const lines = ['# Free-source capability matrix', '', 'Generated from `src/core/registry.js` (documented capability) and `.data/probe-results.json` (live probe). Documented ≠ verified: the last column only says "verified" when a live call succeeded.', ''];
  lines.push('| Source | Product | Needs | Real-time / delay | Volume | Extended hours | History | Limits | Role | Status | Live verification |', '|---|---|---|---|---|---|---|---|---|---|---|');
  for (const s of SOURCES) {
    const v = verified.get(s.id);
    const ver = v ? (v.ok ? `verified ${new Date(v.at).toISOString().slice(0, 10)}: ${JSON.stringify(v.detail)}` : `FAILED ${new Date(v.at).toISOString().slice(0, 10)}: ${v.error}`) : (s.liveVerifiedNote ?? 'not probed (key not configured)');
    lines.push(`| ${s.provider} | ${s.product} | ${s.needs.join(', ') || 'none'} | ${s.realtime} | ${s.volume} | ${s.extendedHours} | ${s.history} | ${s.limits} | ${s.role} | ${s.status} | ${ver.replace(/\|/g, '/')} |`);
  }
  lines.push('', '## Details', '');
  for (const s of SOURCES) {
    lines.push(`### ${s.provider} — ${s.product}`, '', `- Endpoints: ${s.endpoints.join('; ')}`, `- Entitlement: ${s.entitlement}`, `- Coverage: ${s.coverage}`, `- Timestamps: ${s.timestamps}`, `- Restrictions: ${s.restrictions}`, `- Features enabled: ${s.features.join('; ') || '—'}`, `- Fallback: ${s.fallback}`, ...(s.excluded ? [`- Explicitly not used: ${s.excluded.join('; ')}`] : []), '');
  }
  lines.push('## Operating modes', '', ...Object.entries(MODES).map(([k, v]) => `- **${k}**: ${v}`), '', '## Features by profile', '', '| Feature | DEMO | LIVE LIMITED (IEX) | DELAYED (SIP ≥15 min) | ENHANCED (paid) |', '|---|---|---|---|---|', ...PROFILE_FEATURES.map((r) => `| ${r.join(' | ')} |`), '');
  fs.writeFileSync('docs/CAPABILITY_MATRIX.md', lines.join('\n'));
  console.log('written docs/CAPABILITY_MATRIX.md');
}

({ demo, replay: doReplay, validate, registry }[cmd] ?? (() => { console.error('commands: demo | replay <id> | validate | registry'); process.exit(1); }))();
